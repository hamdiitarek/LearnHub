// Regenerates lib/demo/schema.ts from prisma/schema.prisma.
// Run after changing the schema: npm run demo:schema
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execFileSync(
  "npx",
  [
    "prisma",
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema",
    "prisma/schema.prisma",
    "--script",
  ],
  {
    env: {
      ...process.env,
      DATABASE_URL:
        process.env.DATABASE_URL ?? "postgresql://demo@localhost:5432/demo",
    },
    encoding: "utf8",
  },
);

writeFileSync(
  "lib/demo/schema.ts",
  `// Generated by scripts/demo-schema.mjs from prisma/schema.prisma. Do not edit.\nexport const SCHEMA_SQL = ${JSON.stringify(sql)};\n`,
);
console.log("Wrote lib/demo/schema.ts");
